import {
  Box,
  Flex,
  Heading,
  Stack,
  Text,
  VStack,
  HStack,
  useToast,
  StackDivider,
  Button,
  ButtonGroup,
  Textarea,
  Modal,
  ModalOverlay,
  ModalContent,
  ModalHeader,
  ModalCloseButton,
  ModalBody,
  Alert,
  AlertIcon,
  ModalFooter,
  Popover,
  PopoverTrigger,
  PopoverContent,
  PopoverArrow,
  PopoverCloseButton,
  Spinner,
} from "@chakra-ui/react";
import MessageIcon from "../../components/Icons/customPromptIcon/MessageIcon";
import { GoInfo } from "react-icons/go";
import { fetchKnowledgebaseDetails, updatePrompt, defaultBasePromptApi } from "../../services/knowledgebaseService";
import { useState, useEffect } from "react";
import { CurrentUser } from "../../services/appConfig";
import { set } from "lodash";
import { useLocation } from "react-router-dom";

const instruction = `Please follow the following steps to change the default base prompt: \n
1. Copy the default base prompt visible on the left-hand side.
2. Paste it into this text box and modify the base prompt as per your custom requirement.
3. Click on the 'Save Custom Prompt' button below.
4. If you want to reset the prompt to the default prompt, please click on the 'Reset To Default Base Prompt' button below.

Please note:

We do not recommend you to update the custom prompt as it may result in inaccurate/incomplete responses being generated by the bot. In this case, please revert to the default base prompt by following the step number 4 above.`
const CustomPrompt = ({ chatbotId, chatbotType }: any) => {
  const [basePrompt, setBasePrompt] = useState("");
  const [customPromptData, setcustomPromptData] = useState("");
  const [updatePrompts, setUpdatePrompts] = useState(false);
  const toast = useToast();
  const [isOpens, setIsOpens] = useState(false);
  const location = useLocation();
  const queryParams = new URLSearchParams(location.search);
  const tab = queryParams.get('tab');
  const [isOpen, setIsOpen] = useState(false);
  const [isPopoverOpen, setIsPopoverOpen] = useState(false);
  const [isLodading, setIsloging] = useState(false);
  const [isFetchLoading, setIsFetchLoading] = useState(true);
  const onCloses = () => {
    setIsOpens(false);
  };
  const onClose = () => {
    setIsOpen(false);
  };

  // Define fetchData outside the block
  async function fetchData() {
    try {
      const response: any = await fetchKnowledgebaseDetails(chatbotId);
      setIsFetchLoading(false);
      // console.error('response data:', response);
      setBasePrompt(response.data.prompt);
    } catch (error) {
      setIsFetchLoading(false);
      // console.error('Error fetching data:', error);
    }
  }

  useEffect(() => {
    if (tab == "custom-prompt") {
      fetchData(); // Call the function
    }
  }, [tab]);

  const handleCustomPrompt = (e: any) => {
    setcustomPromptData(e.target.value);
  }

  const updatebase = async () => {
    try {
      setIsloging(true);
      const response: any = await updatePrompt(chatbotId, customPromptData);
      setcustomPromptData("");
      fetchData();
      toast({
        title: `Your custom prompt has successfully been added as the base prompt.`,
        status: "success",
        isClosable: true,
      });
    } catch (error: any) {
      toast({
        title: error?.response?.data?.message || `Something went wrong please try again`,
        status: "error",
        isClosable: true,
      });
    } finally {
      setIsOpens(false);
      setIsloging(false);
    }
  }

  async function saveCustomPrompt() {
    try {
      if (customPromptData === "") {
        const userRole = CurrentUser.get();
        // if (userRole.role == "admin" && chatbotType !== "vakmangids") {
        //   toast({
        //     title: `You cannot change the specific settings of the admin's project.`,
        //     status: "error",
        //     isClosable: true,
        //   });
        // } else {
        toast({
          title: `Please enter a custom prompt and then click on the 'Save Custom Prompt' button.`,
          status: "error",
          isClosable: true,
        });
        // }

      }
      else {
        const userRole = CurrentUser.get();
        // if (userRole.role == "admin" && chatbotType !== "vakmangids") {
        //   toast({
        //     title: `You cannot change the specific settings of the admin's project.`,
        //     status: "error",
        //     isClosable: true,
        //   });
        // } else {
        // }
        setIsOpens(true);
      }

    } catch (error: any) {
      toast({
        title: error?.response?.data?.message || `Something went wrong please try again`,
        status: "error",
        isClosable: true,
      });
    } finally {
      setUpdatePrompts(false)
    }
  }

  const updatedefault = async () => {
    try {
      setIsloging(true);
      const response: any = await defaultBasePromptApi(chatbotId);
      setUpdatePrompts(true)
      fetchData();
      // window.location.reload();
      toast({
        title: `The prompt has successfully been reset to the default base prompt.`,
        status: "success",
        isClosable: true,
      });
    } catch (error: any) {
      toast({
        title: error?.response?.data?.message || `Something went wrong please try again`,
        status: "error",
        isClosable: true,
      });
    } finally {
      setIsOpen(false);
      setIsloging(false);
    }
  }

  async function handleDefaultBasePrompt() {
    try {
      const userRole = CurrentUser.get();
      // if (userRole.role == "admin") {
      //   toast({
      //     title: `You cannot change the specific settings of the admin's project.`,
      //     status: "error",
      //     isClosable: true,
      //   });
      // } else {
      // }
      setIsOpen(true);
    } catch (error: any) {
      toast({
        title: error?.response?.data?.message || `Something went wrong please try again`,
        status: "error",
        isClosable: true,
      });
    } finally {
      setUpdatePrompts(false)

    }
  }


  return (
    <>
      {
        isFetchLoading ?
          <Flex justifyContent="center" alignItems="center" height="200px">
            <Spinner />
          </Flex> :
          <>
            <Box borderWidth='1px' borderRadius='lg' >
              <Stack
                divider={<StackDivider mx={'0px !important'} borderColor='gray.200' />}
                direction={["column", "row"]}
                spacing={1}
              >
                <Box p={6} width={["100%", "50%"]}>
                  <Heading fontSize="20px" fontWeight="600" mb={4}>Base Prompt</Heading>
                  <Box color="#6C757D" fontSize="16px" fontWeight="400">
                    <Textarea
                      textAlign="justify"
                      width="100%"
                      borderRadius={'4px'}
                      height="500px"
                      resize="none"
                      value={basePrompt}
                    >
                    </Textarea>
                  </Box>
                </Box>

                <Box p={6} width={["100%", "50%"]}>
                  <Heading fontSize="20px" display={'flex'} alignItems={'center'} gap={2} fontWeight="600" mb={'4px'}>
                    Custom Prompt
                    <Popover isOpen={isPopoverOpen} onClose={() => setIsPopoverOpen(false)}>
                      <PopoverTrigger>
                        <Box
                          cursor="pointer"
                          as="span"
                          onClick={() => setIsPopoverOpen(!isPopoverOpen)}
                        >
                          <GoInfo />
                        </Box>
                      </PopoverTrigger>
                      <PopoverContent
                        bg="#efefef"
                        fontWeight={500}
                        color="#333"
                        p={4}
                        width="250px"
                        fontSize="12px"
                        border="1px solid #ccc"
                        lineHeight="20px"
                        style={{ boxShadow: 'none' }}
                        borderRadius="4px"
                      >
                        <PopoverArrow bg="#efefef" transform="scale(1.5)" />
                        {/* <PopoverCloseButton /> */}
                        <Box whiteSpace="pre-wrap">{instruction}</Box>
                      </PopoverContent>
                    </Popover>
                  </Heading>
                  <Text color="#6C757D" fontSize="16px" fontWeight="400px" mb={4}>If you want to change base prompt you can create your custom prompt</Text>
                  <Box color="#6C757D" fontSize="16px" fontWeight="400">
                    <Textarea
                      textAlign="justify"
                      width="100%"
                      height="447px"
                      borderRadius={'4px'}
                      resize="none"
                      placeholder={`Please enter your custom prompt here`}
                      id="customPromptId"
                      onChange={handleCustomPrompt}
                      value={customPromptData} // Bind state to value
                    >
                    </Textarea>
                  </Box>
                </Box>
              </Stack>
            </Box>
            <Stack direction='row' spacing={4} justifyContent="end" m={6} mb={1}>
              <Button leftIcon={<MessageIcon />} onClick={() => saveCustomPrompt()} colorScheme="blue" className="btn-hover-pri" variant='solid' fontSize="16px" fontWeight="500">
                Save Custom Prompt
              </Button>
              <Button leftIcon={<MessageIcon />} onClick={handleDefaultBasePrompt} colorScheme='#6C757D' variant='solid' bg="#6C757D" fontSize="16px" fontWeight="500" _hover={{ bg: '#51585E' }}>
                Reset To Default Base Prompt
              </Button>
              <Modal isOpen={isOpens} onClose={onCloses} size="xl">
                <ModalOverlay />
                <ModalContent>
                  <ModalHeader>Are you sure you want to update the default base prompt?
                  </ModalHeader>
                  <ModalCloseButton />
                  <ModalFooter>
                    <Button colorScheme='blue' fontWeight="500" mr={3} onClick={updatebase} isDisabled={isLodading}>
                      Yes
                    </Button>
                    <Button colorScheme='gray' fontWeight="500" mr={3} onClick={onCloses}>
                      Close
                    </Button>
                  </ModalFooter>
                </ModalContent>
              </Modal>
              <Modal isOpen={isOpen} onClose={onClose} size="xl">
                <ModalOverlay />
                <ModalContent>
                  <ModalHeader>Are you sure you want to reset the default base prompt?
                  </ModalHeader>
                  <ModalCloseButton />
                  <ModalFooter>
                    <Button colorScheme='blue' fontWeight="500" mr={3} onClick={updatedefault} isDisabled={isLodading}>
                      Yes
                    </Button>
                    <Button colorScheme='gray' fontWeight="500" mr={3} onClick={onClose}>
                      Close
                    </Button>
                  </ModalFooter>
                </ModalContent>
              </Modal>
            </Stack>
          </>
      }
    </>
  );

}
export default CustomPrompt;