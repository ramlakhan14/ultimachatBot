import React from "react";
import {
  Button,
  Text,
  Modal,
  ModalOverlay,
  ModalContent,
  ModalBody,
  ModalHeader,
  ModalCloseButton,
  FormControl,
  FormLabel,
  Input,
  FormErrorMessage,
  Box,
  useToast,
  CheckboxGroup,
  Stack,
  Checkbox,
  Popover,
  PopoverTrigger,
  PopoverContent,
  PopoverArrow
} from "@chakra-ui/react";
import { Controller, useForm } from "react-hook-form";
import { sendBulkLead } from "../../services/zapierservice";
import { GoInfo } from "react-icons/go";

const instruction = `
<strong>Follow these steps to obtain the webhook from Zapier.</strong>
1. <a href="https://zapier.com/app/login" style="color:#2977FF" target="_blank" rel="noopener noreferrer">Create a Zap</a> → Select Webhook as the trigger → Choose "Catch Hook".
2. Copy the Webhook URL generated by Zapier.
3. Paste the Webhook URL into this required field.
4. Ensure the system is running and accessible online.
<strong>Disclaimer:</strong> We are not responsible for changes made by third-party applications. Any updates may affect the process, and users may need to adjust accordingly. We will update the steps once informed.
`
const SyncWithCrmModal = ({ isOpen, onClose }: any) => {
  const {
    handleSubmit,
    control,
    register,
    reset,
    formState: { errors },
  } = useForm({
    defaultValues: {
      webhookUrl: "",
      leadType: [],
    },
  });
  const [isSubmitting, setIsSubmitting] = React.useState<boolean>(false);
  const [isPopoverOpen, setIsPopoverOpen] = React.useState(false);

  const toast = useToast();

  const onSubmit = async (data: any) => {
    // console.log(data);
    try {
      setIsSubmitting(true);
      const res: any = await sendBulkLead(data);
      // console.log(res)
      if (res.status === 200) {
        toast({
          title: res.data.message,
          status: "success",
          isClosable: true,
        });
        reset();
        onClose();

      }
    } catch (error: any) {
      toast({
        title: `${error.response.data.message}`,
        status: "error",
        isClosable: true,
      });
    } finally {
      setIsSubmitting(false);
    }
  }
  const closeModal = () => {
    reset();
    onClose();
  }
  return (
    <Modal isOpen={isOpen} size="xl" onClose={onClose} closeOnOverlayClick={false}>
      <ModalOverlay />
      <ModalContent bg="#F7FAFC">
        <ModalCloseButton _focus={{ outline: "none" }} />
        <ModalHeader textAlign="center" fontSize="18px" fontWeight="700" color="#1A202C" pb="8px" pt={'24px'}>Sync with Zapier</ModalHeader>
        <Text as="span" textAlign="center" fontSize="14px" fontWeight="400" color="#6C757D" pb="24px">Enhance customer interactions and manage data effortlessly across platforms.</Text>
        <ModalBody py={0}>
          <form onSubmit={handleSubmit(onSubmit)}>
            <FormControl isInvalid={!!errors.leadType} mb={4}>
              <FormLabel display={'flex'} alignItems={'center'} gap={'4px'}>Lead Type <Text as={"span"} fontSize="16px" fontWeight={"400"} style={{ color: "#DC3545" }}>*</Text></FormLabel>
              <Controller
                name="leadType"
                control={control}
                rules={{ validate: (value) => value.length > 0 || "At least one option is required" }}
                render={({ field }) => (
                  <CheckboxGroup {...field}>
                    <Stack spacing={2}>
                      <Checkbox borderColor="#6C757D"
                        sx={{
                          ".chakra-checkbox__control": {
                            border: "1px solid #6C757D",
                          },
                        }} width={"100px"} value="chatBot"><Text as="span" fontSize={'14px'}>ChatBot</Text></Checkbox>
                      <Checkbox borderColor="#6C757D"
                        sx={{
                          ".chakra-checkbox__control": {
                            border: "1px solid #6C757D",
                          },
                        }} width={"100px"} value="voiceBot"><Text as="span" fontSize={'14px'}>VoiceBot</Text></Checkbox>
                      <Checkbox borderColor="#6C757D"
                        sx={{
                          ".chakra-checkbox__control": {
                            border: "1px solid #6C757D",
                          },
                        }} width={"130px"} value="emailAssistant"><Text as="span" fontSize={'14px'}>Email Assistant</Text>
                      </Checkbox>
                      <Checkbox borderColor="#6C757D"
                        sx={{
                          ".chakra-checkbox__control": {
                            border: "1px solid #6C757D",
                          },
                        }} width={"130px"} value="emailOutreach"><Text as="span" fontSize={'14px'}>Email Outreach</Text>
                      </Checkbox>
                      {/* <Checkbox borderColor="#6C757D"
                        sx={{
                          ".chakra-checkbox__control": {
                            border: "1px solid #6C757D",
                          },
                        }} width={"100px"} value="mailBot"><Text as="span" fontSize={'14px'}>MailBot</Text>
                      </Checkbox> */}
                    </Stack>
                  </CheckboxGroup>
                )}
              />
              <FormErrorMessage>{errors.leadType?.message}</FormErrorMessage>
            </FormControl>
            <FormControl isInvalid={!!errors.webhookUrl} mb={4}>
              <FormLabel display={'flex'} alignItems={'center'} gap={'4px'}>Webhook URL
                <Popover isOpen={isPopoverOpen} onClose={() => setIsPopoverOpen(false)}>
                  <PopoverTrigger>
                    <Box
                      cursor="pointer"
                      as="span"
                      onClick={() => setIsPopoverOpen(!isPopoverOpen)}
                    >
                      <GoInfo color="#6C757D" />
                    </Box>
                  </PopoverTrigger>
                  <PopoverContent
                    bg="#efefef"
                    fontWeight={500}
                    color="#333"
                    p={4}
                    pt={0}
                    width="300px"
                    fontSize="12px"
                    border="1px solid #ccc"
                    lineHeight="20px"
                    style={{ boxShadow: 'none' }}
                    borderRadius="4px"
                  >
                    <PopoverArrow bg="#efefef" transform="scale(1.5)" />
                    {/* <PopoverCloseButton /> */}
                    <Box whiteSpace="pre-wrap" lineHeight={"25px"} dangerouslySetInnerHTML={{ __html: instruction }}></Box>
                  </PopoverContent>
                </Popover>
                <Text as={"span"} fontSize="16px" fontWeight={"400"} style={{ color: "#DC3545" }}>*</Text>
              </FormLabel>
              <Input
                type="text"
                placeholder="Enter webhook URL"
                {...register("webhookUrl", {
                  required: "Webhook URL is required",
                  pattern: {
                    value: /^(https?:\/\/)[^\s/$.?#].[^\s]*$/i,
                    message: "Please enter a valid URL",
                  },
                })}
              />
              <FormErrorMessage>{errors.webhookUrl?.message}</FormErrorMessage>
            </FormControl>
            <Box textAlign="end" mb={4}>
              <Button
                colorScheme="gray"
                size='md'
                mr="12px"
                fontWeight={500}
                onClick={closeModal}
              >
                Cancel
              </Button>
              <Button
                colorScheme="blue"
                size="md"
                type="submit"
                fontWeight={500}
                isLoading={isSubmitting}
              >
                Sync
              </Button>
            </Box>
          </form>
        </ModalBody>
      </ModalContent>
    </Modal>
  )
}

export default SyncWithCrmModal;